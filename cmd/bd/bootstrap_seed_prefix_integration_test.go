// writeUnprovisionedServerWorkspace writes dir/.beads for a server-mode workspace on
// the test Dolt server, the way a provisioner that never ran bd init leaves
// it: metadata.json names the server and database but carries no project_id,
// there is no local shadow directory, and config.yaml names the issue prefix
// and turns off auto-start.
func writeUnprovisionedServerWorkspace(t *testing.T, dir, database string, port int) string {
	t.Helper()
	beadsDir := filepath.Join(dir, ".beads")
	if err := os.MkdirAll(beadsDir, 0o700); err != nil {
		t.Fatal(err)
	}
	meta := fmt.Sprintf(`{"backend":"dolt","database":"dolt","dolt_mode":"server","dolt_server_host":"127.0.0.1","dolt_server_port":%d,"dolt_database":%q}`, port, database)
	if err := os.WriteFile(filepath.Join(beadsDir, "metadata.json"), []byte(meta), 0o644); err != nil {
		t.Fatal(err)
	}
	yaml := "issue-prefix: la\ndolt:\n  auto-start: false\n"
	if err := os.WriteFile(filepath.Join(beadsDir, "config.yaml"), []byte(yaml), 0o644); err != nil {
		t.Fatal(err)
	}
	return beadsDir
}

// testServerSQL runs fn against the test Dolt server with no database
// selected.
func testServerSQL(t *testing.T, fn func(ctx context.Context, db *sql.DB) error) {
	t.Helper()
	db, err := sql.Open("mysql", doltutil.ServerDSN{Host: "127.0.0.1", Port: testDoltServerPort, User: "root"}.String())
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	if err := fn(ctx, db); err != nil {
		t.Fatal(err)
	}
}

// serverIssuePrefix returns database's issue_prefix row on the test server,
// or "" when it has none.
func serverIssuePrefix(t *testing.T, database string) (string, error) {
	t.Helper()
	var value string
	var queryErr error
	testServerSQL(t, func(ctx context.Context, db *sql.DB) error {
		//nolint:gosec // G201: database is generated by uniqueTestDBName
		queryErr = db.QueryRowContext(ctx, fmt.Sprintf("SELECT value FROM `%s`.config WHERE `key` = 'issue_prefix'", database)).Scan(&value)
		if queryErr == sql.ErrNoRows {
			queryErr = nil
		}
		return nil
	})
	return value, queryErr
}

// createServerDatabaseWithoutPrefix creates database on the test server with
// the full Beads schema and no issue_prefix row, from a scratch directory so
// the workspace under test gains no local state. A database with the schema
// is a candidate in bootstrap's metadata reconcile, which therefore cannot
// redirect the workspace to the server's only other Beads database.
func createServerDatabaseWithoutPrefix(t *testing.T, database string) {
	t.Helper()
	scratch := filepath.Join(t.TempDir(), ".beads")
	store, err := dolt.New(context.Background(), &dolt.Config{
		Path:            filepath.Join(scratch, "dolt"),
		BeadsDir:        scratch,
		ServerHost:      "127.0.0.1",
		ServerPort:      testDoltServerPort,
		Database:        database,
		CreateIfMissing: true,
	})
	if err != nil {
		t.Fatalf("create server database %s: %v", database, err)
	}
	if err := store.Close(); err != nil {
		t.Fatalf("close store: %v", err)
	}
	if got, err := serverIssuePrefix(t, database); err != nil || got != "" {
		t.Fatalf("fixture database issue_prefix = %q (err %v), want no row", got, err)
	}
}

func bootstrapServerTestEnv() []string {
	return append(os.Environ(), "BD_DISABLE_METRICS=1", "DO_NOT_TRACK=1")
}

// AC-1 (GH#3494): a server-mode workspace with no project_id and no local
// shadow directory, whose database exists on the server with no
// issue_prefix, gets its prefix from config.yaml written into that server
// database. Bootstrap used to fall through to "init", create an unrelated
// embedded database under .beads/embeddeddolt and print "Created fresh
// database", while bd config get and bd create still read the server.
func TestCLI_Bootstrap_SeedsServerDatabaseMissingPrefix_E2E(t *testing.T) {
	skipIfNoDolt(t)

	dir := t.TempDir()
	database := uniqueTestDBName(t)
	t.Cleanup(func() { dropTestDatabase(database, testDoltServerPort) })
	createServerDatabaseWithoutPrefix(t, database)
	beadsDir := writeUnprovisionedServerWorkspace(t, dir, database, testDoltServerPort)
	env := bootstrapServerTestEnv()

	stdout, stderr, err := runBDExecSeparated(t, testBD, dir, env, "bootstrap", "--yes")
	if err != nil {
		t.Fatalf("bd bootstrap --yes: %v\nstdout:\n%s\nstderr:\n%s", err, stdout, stderr)
	}
	if strings.Contains(stdout+stderr, "Created fresh database") {
		t.Errorf("bootstrap created a fresh database instead of seeding the existing one:\nstdout:\n%s\nstderr:\n%s", stdout, stderr)
	}
	if _, err := os.Stat(filepath.Join(beadsDir, "embeddeddolt")); err == nil {
		t.Errorf("bootstrap created .beads/embeddeddolt in a server-mode workspace")
	}

	if got, err := serverIssuePrefix(t, database); err != nil || got != "la" {
		t.Errorf("server database issue_prefix = %q (err %v), want %q\nbootstrap stdout:\n%s\nstderr:\n%s", got, err, "la", stdout, stderr)
	}

	got, getErr, err := runBDExecSeparated(t, testBD, dir, env, "config", "get", "issue_prefix")
	if err != nil {
		t.Fatalf("bd config get issue_prefix: %v\n%s%s", err, got, getErr)
	}
	if strings.TrimSpace(got) != "la" {
		t.Errorf("bd config get issue_prefix = %q, want %q", strings.TrimSpace(got), "la")
	}

	id, createErr, err := runBDExecSeparated(t, testBD, dir, env, "create", "--type", "task", "--title", "x", "--silent")
	if err != nil {
		t.Fatalf("bd create after bootstrap: %v\n%s%s", err, id, createErr)
	}
	if !strings.HasPrefix(strings.TrimSpace(id), "la-") {
		t.Errorf("bd create after bootstrap made %q, want an la- id", strings.TrimSpace(id))
	}
}

// AC-3: a server-mode workspace whose database is absent on the server gets
// it, and its issue_prefix, created on that server by the init and
// jsonl-import actions, the same server every later command reads. Those
// actions used to open the command's default backend, so they created an
// embedded database under .beads/embeddeddolt that nothing else reads.
func TestCLI_Bootstrap_ProvisionsMissingServerDatabase_E2E(t *testing.T) {
	skipIfNoDolt(t)

	// A second Beads database on the server, so bootstrap's metadata
	// reconcile has no sole schema candidate to redirect the workspace to.
	decoy := uniqueTestDBName(t)
	t.Cleanup(func() { dropTestDatabase(decoy, testDoltServerPort) })
	createServerDatabaseWithoutPrefix(t, decoy)

	for _, tc := range []struct {
		name    string
		jsonl   string
		wantOut string
	}{
		{name: "init", wantOut: `Created fresh database with prefix "la"`},
		{
			name:    "jsonl-import",
			jsonl:   `{"id":"la-1","title":"imported","status":"open","priority":2,"issue_type":"task","created_at":"2026-01-01T00:00:00Z","updated_at":"2026-01-01T00:00:00Z"}` + "\n",
			wantOut: "Imported 1 issues",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			database := uniqueTestDBName(t)
			t.Cleanup(func() { dropTestDatabase(database, testDoltServerPort) })
			beadsDir := writeUnprovisionedServerWorkspace(t, dir, database, testDoltServerPort)
			if tc.jsonl != "" {
				if err := os.WriteFile(filepath.Join(beadsDir, "issues.jsonl"), []byte(tc.jsonl), 0o644); err != nil {
					t.Fatal(err)
				}
			}

			stdout, stderr, err := runBDExecSeparated(t, testBD, dir, bootstrapServerTestEnv(), "bootstrap", "--yes")
			if err != nil {
				t.Fatalf("bd bootstrap --yes: %v\nstdout:\n%s\nstderr:\n%s", err, stdout, stderr)
			}
			if !strings.Contains(stdout+stderr, tc.wantOut) {
				t.Errorf("bootstrap output lacks %q:\nstdout:\n%s\nstderr:\n%s", tc.wantOut, stdout, stderr)
			}
			if _, err := os.Stat(filepath.Join(beadsDir, "embeddeddolt")); err == nil {
				t.Errorf("bootstrap created .beads/embeddeddolt in a server-mode workspace")
			}
			if got, err := serverIssuePrefix(t, database); err != nil || got != "la" {
				t.Errorf("server database issue_prefix = %q (err %v), want %q\nbootstrap stdout:\n%s\nstderr:\n%s", got, err, "la", stdout, stderr)
			}
		})
	}
}

// AC-3: the init action fails when the workspace's server cannot be reached,
// instead of creating an embedded database and reporting "Created fresh
// database".
func TestBootstrapInitAction_UnreachableServerFails(t *testing.T) {
	// The package's TestMain exports the test server's port, which would
	// replace the dead port metadata.json names.
	t.Setenv("BEADS_DOLT_PORT", "")
	t.Setenv("BEADS_DOLT_SERVER_PORT", "")
	database := uniqueTestDBName(t)
	t.Cleanup(func() { dropTestDatabase(database, testDoltServerPort) })
	beadsDir := writeUnprovisionedServerWorkspace(t, t.TempDir(), database, freeLoopbackPort(t))
	cfg, err := configfile.Load(beadsDir)
	if err != nil {
		t.Fatal(err)
	}
	plan := BootstrapPlan{Action: "init", BeadsDir: beadsDir, Database: cfg.GetDoltDatabase()}

	if err := executeInitAction(context.Background(), plan, cfg); err == nil {
		t.Fatal("executeInitAction succeeded against an unreachable Dolt server")
	}
	if _, err := os.Stat(filepath.Join(beadsDir, "embeddeddolt")); err == nil {
		t.Errorf("executeInitAction created .beads/embeddeddolt in a server-mode workspace")
	}
}
