func TestRelPath(t *testing.T) {
	for _, c := range []struct{ dir, name, want string }{
		{"/x/root", "/x/root/cmd/bd/a.go", "cmd/bd/a.go"},
		{"/x/root", "cmd/bd/a.go", "cmd/bd/a.go"},
		{"", "/abs/a.go", "/abs/a.go"},
	} {
		if got := golangci.RelPath(c.dir, c.name); got != c.want {
			t.Errorf("RelPath(%q, %q) = %q, want %q", c.dir, c.name, got, c.want)
		}
	}
}
