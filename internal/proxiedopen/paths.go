const managedListenerHostRemediation = "set listener.host to 127.0.0.1 (or another 127.0.0.0/8 / ::1 " +
	"loopback address); for non-local topology use " +
	"--proxied-server-external-host with --proxied-server-external-port, " +
	"--proxied-server-external-socket-path, or switch to non-proxied server mode"

// ManagedConfigMarker is the first line of every managed-local config.yaml
// Beads generates. Its presence is what lets ManagedPortConflictPolicy treat a
// listener port as one Beads chose rather than one an operator pinned.
const ManagedConfigMarker = "# Generated by Beads on first run - safe to delete (will be regenerated). " +
	"Never rewritten afterward; hand edits are preserved. See gastownhall/beads#4986.\n"

// IsManagedConfig reports whether body is a Beads-generated config (it starts
// with ManagedConfigMarker).
func IsManagedConfig(body []byte) bool {
	return bytes.HasPrefix(body, []byte(ManagedConfigMarker))
}

// ConfigFileName and LogFileName are the default managed-local config and
// server log names, inside the resolved proxied-server root.
const (
	ConfigFileName = "config.yaml"
	LogFileName    = "server.log"
)

func envOrAbsJoin(envName, beadsDir string) string {
	p := os.Getenv(envName)
	if p == "" {
		return ""
	}
	if filepath.IsAbs(p) {
		return p
	}
	return filepath.Join(beadsDir, p)
}

// ResolveRootPath delegates to the exported implementation in
// internal/doltserver so the workspace-gate resolver and the proxy plumbing
// share one root derivation (env → client-info sidecar → default data dir)
// and cannot drift. Note the shared implementation resolves the default via
// the side-effect-free DoltDirPath — same path as doltserver.ResolveDoltDir, but it
// never mkdirs the shared-server tree just to answer "where is the root".
func ResolveRootPath(beadsDir string) (string, error) {
	return doltserver.ResolveProxiedServerRootPath(beadsDir)
}

// ResolveConfigPath resolves the managed-local dolt sql-server config:
// BEADS_PROXIED_SERVER_CONFIG, then the sidecar's config path (both custom),
// then <root>/config.yaml (Beads' default, which EnsureConfig may create).
func ResolveConfigPath(beadsDir string) (path string, isCustom bool, err error) {
	if p := envOrAbsJoin("BEADS_PROXIED_SERVER_CONFIG", beadsDir); p != "" {
		return p, true, nil
	}
	info, err := configfile.LoadProxiedServerClientInfo(beadsDir)
	if err != nil {
		return "", false, err
	}
	if p := info.ResolvedConfigPath(beadsDir); p != "" {
		return p, true, nil
	}
	root, err := ResolveRootPath(beadsDir)
	if err != nil {
		return "", false, err
	}
	return filepath.Join(root, ConfigFileName), false, nil
}

// ResolveLogPath resolves the proxied server log the same way: the
// BEADS_PROXIED_SERVER_LOG env var, then the sidecar's log path (both
// custom, so the operator owns them), then <root>/server.log.
func ResolveLogPath(beadsDir string) (path string, isCustom bool, err error) {
	if p := envOrAbsJoin("BEADS_PROXIED_SERVER_LOG", beadsDir); p != "" {
		return p, true, nil
	}
	info, err := configfile.LoadProxiedServerClientInfo(beadsDir)
	if err != nil {
		return "", false, err
	}
	if p := info.ResolvedLogPath(beadsDir); p != "" {
		return p, true, nil
	}
	root, err := ResolveRootPath(beadsDir)
	if err != nil {
		return "", false, err
	}
	return filepath.Join(root, LogFileName), false, nil
}

// EnsureConfig resolves the managed-local config, generating Beads' default
// one when it is absent, and validates it against the managed trust boundary
// (ValidateConfig). A custom config is never created, only checked.
func EnsureConfig(beadsDir string) (string, error) {
	path, err := resolveOrCreateConfig(beadsDir)
	if err != nil {
		return "", err
	}
	if err := ValidateConfig(path); err != nil {
		return "", fmt.Errorf("ensureProxiedServerConfig: %w", err)
	}
	return path, nil
}

func resolveOrCreateConfig(beadsDir string) (string, error) {
	path, isCustom, err := ResolveConfigPath(beadsDir)
	if err != nil {
		return "", err
	}

	if isCustom {
		info, err := os.Stat(path)
		if err != nil {
			return "", fmt.Errorf("ensureProxiedServerConfig: custom config %s: %w", path, err)
		}
		if !info.Mode().IsRegular() {
			return "", fmt.Errorf("ensureProxiedServerConfig: custom config %s: not a regular file", path)
		}
		return path, nil
	}

	root := filepath.Dir(path)
	if err := os.MkdirAll(root, config.BeadsDirPerm); err != nil {
		return "", fmt.Errorf("ensureProxiedServerConfig: mkdir %s: %w", root, err)
	}

	switch _, err := os.Stat(path); {
	case err == nil:
		return path, nil
	case !os.IsNotExist(err):
		return "", fmt.Errorf("ensureProxiedServerConfig: stat %s: %w", path, err)
	}

	port, err := proxy.PickFreePort()
	if err != nil {
		return "", fmt.Errorf("ensureProxiedServerConfig: pick free port: %w", err)
	}

	body, err := RenderConfig(port)
	if err != nil {
		return "", fmt.Errorf("ensureProxiedServerConfig: render YAML: %w", err)
	}
	if err := atomicWriteFile(resolveConfigWriteTarget(path), body); err != nil {
		return "", fmt.Errorf("ensureProxiedServerConfig: write %s: %w", path, err)
	}
	return path, nil
}

// resolveConfigWriteTarget resolves path to its physical location before
// an atomic rewrite. os.Rename's destination argument does not follow
// symlinks — it unlinks and replaces whatever is AT that path, symlink or
// not — so writing straight to a symlinked config.yaml would silently
// replace the symlink itself with a regular file instead of updating the
// file it points at. Falls back to path unresolved when it does not exist
// yet (filepath.EvalSymlinks errors on a missing path), which covers both
// the ordinary "no config.yaml yet" case and a dangling symlink.
func resolveConfigWriteTarget(path string) string {
	resolved, err := filepath.EvalSymlinks(path)
	if err != nil {
		return path
	}
	return resolved
}

// Validators below emit source-neutral errors. Callers wrap with whichever
// label is meaningful at their site: CLI callers prepend the flag name
// (e.g. "--proxied-server-config-path"); runtime callers (uow factory, etc.)
// prepend whatever label fits — the path may have come from env var or
// the proxied_server_client_info.json sidecar, not necessarily a flag.

// ValidateConfig parses the config at path and applies
// ValidateManagedServerConfigPolicy to it.
func ValidateConfig(path string) error {
	info, err := os.Stat(path)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if !info.Mode().IsRegular() {
		return fmt.Errorf("%s: not a regular file", path)
	}
	cfg, err := servercfg.YamlConfigFromFile(filesys.LocalFS, path)
	if err != nil {
		return fmt.Errorf("%s: parse: %w", path, err)
	}
	if err := ValidateManagedServerConfigPolicy(cfg); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

// ValidateManagedServerConfigPolicy enforces the trust boundary for the Dolt
// child that Beads launches with root and an empty password: every listener
// the config can open must stay loopback-only, so the whole config is in
// scope, not just listener.host. External proxied topology never calls this
// validator because it launches no managed child.
func ValidateManagedServerConfigPolicy(cfg servercfg.ServerConfig) error {
	// listener.host policy: an explicit numeric loopback IP, nothing else.
	// An omitted host is rejected rather than trusted: servercfg resolves it
	// to DefaultHost ("localhost"), and CheckForUnixSocket treats a
	// "localhost" host as license to also open the shared-namespace default
	// unix socket — strictly worse than the explicit hostname it looks like.
	if yc, ok := cfg.(*servercfg.YAMLConfig); ok && yc.ListenerConfig.HostStr == nil {
		return fmt.Errorf(
			"managed proxied-server listener.host is omitted (Dolt would default to %q, "+
				"which can also open the default unix socket) and must be a numeric loopback IP literal: %s",
			servercfg.DefaultHost, managedListenerHostRemediation,
		)
	}
	host := cfg.Host()
	ip := net.ParseIP(host)
	if ip == nil || !ip.IsLoopback() {
		return fmt.Errorf(
			"managed proxied-server listener.host %q must be a numeric loopback IP literal: %s",
			host, managedListenerHostRemediation,
		)
	}
	// A unix socket bypasses the loopback TCP trust boundary entirely
	// (shared filesystem namespace). Socket() maps an explicitly empty
	// listener.socket to Dolt's default socket path, so it is rejected too.
	if socket := cfg.Socket(); socket != "" {
		return fmt.Errorf(
			"managed proxied-server config sets listener.socket %q, which bypasses the loopback trust boundary: "+
				"remove listener.socket; %s",
			socket, managedListenerHostRemediation,
		)
	}
	// remotesapi.port opens an HTTP+gRPC listener on all interfaces; there
	// is no host knob for it, so its presence alone breaks the boundary.
	if port := cfg.RemotesapiPort(); port != nil {
		return fmt.Errorf(
			"managed proxied-server config sets remotesapi.port %d, which listens on all interfaces: "+
				"remove the remotesapi block; %s",
			*port, managedListenerHostRemediation,
		)
	}
	// cluster.remotesapi.port likewise listens on all interfaces.
	if cfg.ClusterConfig() != nil {
		return fmt.Errorf(
			"managed proxied-server config sets a cluster block, whose remotesapi listens on all interfaces: "+
				"remove the cluster block; %s",
			managedListenerHostRemediation,
		)
	}
	return nil
}

// ValidateRootPath accepts an absent path or a directory.
func ValidateRootPath(path string) error {
	switch info, err := os.Stat(path); {
	case err == nil:
		if !info.IsDir() {
			return fmt.Errorf("%s: not a directory", path)
		}
	case !os.IsNotExist(err):
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

// ValidateLogPath accepts an absent path or a regular file whose parent
// directory exists.
func ValidateLogPath(path string) error {
	parent := filepath.Dir(path)
	parentInfo, err := os.Stat(parent)
	if err != nil {
		return fmt.Errorf("%s: parent directory: %w", path, err)
	}
	if !parentInfo.IsDir() {
		return fmt.Errorf("%s: parent %s is not a directory", path, parent)
	}
	switch info, err := os.Stat(path); {
	case err == nil:
		if !info.Mode().IsRegular() {
			return fmt.Errorf("%s: not a regular file", path)
		}
	case !os.IsNotExist(err):
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

// proxiedServerLogLevel is the log_level of a Beads-generated proxied-server
// config on a host that can prove which process holds a listener. dolt logs
// every NewConnection and ConnectionClosed at info, and every bd command
// opens connections through the proxy, so at info a long-running proxied
// server.log grows with each command. warning keeps dolt's warnings and
// errors, as doltServerLogLevel does for server mode. The level hides dolt's
// info-level ready line, so the proxied DoltServer proves readiness by
// listener ownership instead (see its waitReady). To debug, set log_level in
// the generated config: Beads never rewrites it, and editing log_level does
// not pin its listener port.
const proxiedServerLogLevel = servercfg.LogLevel_Warning

// ListenerOwnershipProvable is doltserver.ListenerOwnershipProvable; tests
// (including cmd/bd's) replace it.
var ListenerOwnershipProvable = doltserver.ListenerOwnershipProvable

// generatedProxiedServerLogLevel is the log_level RenderConfig
// writes. Where this host cannot prove listener ownership (Windows, WSL1,
// some sandboxes), proxiedServerLogLevel would leave the proxied DoltServer
// no proof that the listener on its port is the dolt it started: a port
// another process took first would pass as ready and never be moved (#7184).
// There the config stays at info, whose ready line is that proof, and the
// running proxy's log rotation still bounds server.log.
func generatedProxiedServerLogLevel() servercfg.LogLevel {
	if ListenerOwnershipProvable() {
		return proxiedServerLogLevel
	}
	return servercfg.LogLevel_Info
}

// RenderConfig renders Beads' default managed-local config listening on port.
func RenderConfig(port int) ([]byte, error) {
	return renderConfigAtLevel(port, generatedProxiedServerLogLevel())
}

// renderConfigAtLevel renders the managed config at logLevel.
// Configs generated before proxiedServerLogLevel existed used info, and
// RenderLegacyConfig must reproduce them byte for byte.
func renderConfigAtLevel(port int, level servercfg.LogLevel) ([]byte, error) {
	host := ListenerHost
	logLevel := string(level)
	yc := &servercfg.YAMLConfig{
		LogLevelStr: &logLevel,
		ListenerConfig: servercfg.ListenerYAMLConfig{
			HostStr:    &host,
			PortNumber: &port,
		},
	}
	archiveLevel := 0
	yc.BehaviorConfig.AutoGCBehavior = &servercfg.AutoGCBehaviorYAMLConfig{
		ArchiveLevel_: &archiveLevel,
	}
	body, err := yaml.Marshal(yc)
	if err != nil {
		return nil, err
	}
	out := []byte(ManagedConfigMarker + managedPortRecordLine(port))
	return append(out, body...), nil
}

// ListenerHost is the loopback listener.host every generated config uses.
const ListenerHost = "127.0.0.1"

// ManagedPortRecordPrefix starts the comment line, right after the managed
// marker, that records the listener port Beads chose. The dolt sql-server
// binds that port only after the proxy child starts it, so another process
// can take it first; the record lets the child tell a port Beads chose from
// one an operator set (see ManagedPortConflictPolicy). The file itself is
// still never rewritten: a moved port lives only in the proxy child's runtime
// config (server.RuntimeConfigFileName).
const ManagedPortRecordPrefix = "# beads-chosen-listener-port: "

func managedPortRecordLine(port int) string {
	return fmt.Sprintf("%s%d (Beads chose this port. If another process holds it when the server starts, Beads runs the server on a free port for that run, without editing this file. To pin a port, set listener.port to another value or delete this line.)\n",
		ManagedPortRecordPrefix, port)
}

// RenderLegacyConfig is RenderConfig as it was
// before the port record existed: the marker followed directly by the YAML,
// at log_level info.
func RenderLegacyConfig(port int) ([]byte, error) {
	body, err := renderConfigAtLevel(port, servercfg.LogLevel_Info)
	if err != nil {
		return nil, err
	}
	return append([]byte(ManagedConfigMarker), body[len(ManagedConfigMarker)+len(managedPortRecordLine(port)):]...), nil
}

// ManagedPortConflictPolicy is the managed-local backend's
// server.PortConflictPolicy. It lets the proxy child run the dolt sql-server
// on a free port (through a runtime config; configPath is never modified)
// only when configPath's listener.port is a port Beads chose:
//   - the file carries the managed marker and the port record, and
//     listener.port still equals the recorded port; or
//   - the file is byte-identical to a config Beads generated before the
//     record existed (any hand edit makes the bytes differ).
//
// Anything else (an operator's own config, a hand-set port, a hand-edited
// legacy config) is pinned, and the error says what to do.
func ManagedPortConflictPolicy(configPath string, inUsePort int) error {
	body, err := os.ReadFile(configPath) // #nosec G304 -- the proxy child's own --config path
	if err != nil {
		return fmt.Errorf("read %s: %w", configPath, err)
	}
	remedy := fmt.Sprintf("free port %d, or set listener.port in %s to a free port", inUsePort, configPath)
	if !IsManagedConfig(body) {
		return fmt.Errorf("%s is not a Beads-generated config, so its port is pinned; %s", configPath, remedy)
	}
	remedy += ", or delete " + configPath + " so Beads regenerates it"
	cfg, err := servercfg.NewYamlConfig(body)
	if err != nil {
		return fmt.Errorf("parse %s: %w", configPath, err)
	}
	current := cfg.Port()
	if current != inUsePort {
		return fmt.Errorf("%s: listener.port is %d, not the in-use port %d; %s", configPath, current, inUsePort, remedy)
	}
	if recorded, _, ok := CutManagedPortRecord(body[len(ManagedConfigMarker):]); ok {
		if current != recorded {
			return fmt.Errorf("%s: listener.port %d was set by hand (Beads chose %d), so it is pinned; %s", configPath, current, recorded, remedy)
		}
		return nil
	}
	legacy, err := RenderLegacyConfig(current)
	if err != nil {
		return fmt.Errorf("render legacy config: %w", err)
	}
	if bytes.Equal(body, legacy) {
		return nil
	}
	return fmt.Errorf("%s was edited by hand and has no %q record, so its listener.port is pinned; %s",
		configPath, strings.TrimSpace(ManagedPortRecordPrefix), remedy)
}

// CutManagedPortRecord splits the port record line off the front of rest
// (the managed config after its marker) and returns the recorded port and
// the remaining YAML. The digits must end at a space or the line end and
// name a valid TCP port.
func CutManagedPortRecord(rest []byte) (port int, yamlBody []byte, ok bool) {
	if !bytes.HasPrefix(rest, []byte(ManagedPortRecordPrefix)) {
		return 0, nil, false
	}
	line, after, found := bytes.Cut(rest, []byte("\n"))
	if !found {
		return 0, nil, false
	}
	digits := line[len(ManagedPortRecordPrefix):]
	end := 0
	for end < len(digits) && digits[end] >= '0' && digits[end] <= '9' {
		end++
	}
	if end == 0 || (end < len(digits) && digits[end] != ' ') {
		return 0, nil, false
	}
	port, err := strconv.Atoi(string(digits[:end]))
	if err != nil || port < 1 || port > 65535 {
		return 0, nil, false
	}
	return port, after, true
}

// atomicWriteFile writes data to path through a temp file in the same
// directory and a rename, so a reader never sees a partial config. It is
// cmd/bd's helper of the same name (backup_export.go), copied rather than
// shared because that one lives in package main.
func atomicWriteFile(path string, data []byte) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".backup-tmp-*")
	if err != nil {
		return fmt.Errorf("failed to create temp file: %w", err)
	}
	tmpPath := tmp.Name()

	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmpPath)
		return fmt.Errorf("failed to write temp file: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmpPath)
		return fmt.Errorf("failed to sync temp file: %w", err)
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(tmpPath)
		return fmt.Errorf("failed to close temp file: %w", err)
	}
	if err := os.Rename(tmpPath, path); err != nil {
		_ = os.Remove(tmpPath)
		return fmt.Errorf("failed to rename temp file: %w", err)
	}
	return nil
}
