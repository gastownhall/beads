// The structural parity guard.
//
// The first attempt at unit-of-work hooks overrode a HAND-PICKED list of use
// case methods, which is a coverage claim that decays silently: the list is
// right the day it is written and wrong the first time someone adds a verb.
// This file replaces the claim with a PARTITION. Every method of every surface
// the notifying wrapper stands in front of is either recorded or listed below
// with the reason it records nothing, and the tests fail on anything that is
// neither, on anything that is both, and on an exemption that no longer names a
// real method.
//
// Adding a mutating verb to a use case therefore breaks this test until someone
// decides what hook it fires. That decision is the point.
//
// WHY REFLECTION AND A WRITTEN PARTITION rather than deriving "is this a
// mutator?" from the SQL each method reaches (the shape a journal completeness
// guard uses): the derivation needs a call graph, and a name-resolved one over
// domain + domain/db + issueops collapses — every repository body calls
// rows.Close(), which resolves to IssueSQLRepository.Close, so every read looks
// like a mutation. Dropping issueops from the scan loses the closes instead,
// which is the half that matters most here. A partition needs no classifier and
// cannot drift: the compiler supplies the method set, and reflection tells a
// DECLARED override from one promoted by the embedded interface.

// declaredOn reports whether typ declares name itself rather than inheriting it
// from an embedded field. The compiler reports a promoted method's
// implementation as living in "<autogenerated>" — the same discriminator
// internal/storage/role_accessor_decorator_test.go uses, and the only way to
// tell "wrapped" from "passed straight through" on a type that embeds the
// surface it decorates.
func declaredOn(typ reflect.Type, name string) (declared, exists bool) {
	method, ok := typ.MethodByName(name)
	if !ok {
		return false, false
	}
	file, _ := runtime.FuncForPC(method.Func.Pointer()).FileLine(method.Func.Pointer())
	return !strings.Contains(file, "<autogenerated>"), true
}

// assertPartition is the shared body of every guard below: recorded and
// exempted must together cover surface exactly, with no overlap and no
// exemption for a method that no longer exists.
func assertPartition(t *testing.T, what string, surface []string, recorder reflect.Type, exempt map[string]string) {
	t.Helper()
	present := make(map[string]bool, len(surface))
	for _, name := range surface {
		present[name] = true
		declared, exists := declaredOn(recorder, name)
		reason, exempted := exempt[name]
		switch {
		case exempted && declared:
			t.Errorf("%s.%s is both recorded and exempted (%q) — delete the exemption", what, name, reason)
		case exempted && strings.TrimSpace(reason) == "":
			t.Errorf("%s.%s is exempted with no reason", what, name)
		case exempted:
		case declared:
		case !exists:
			t.Errorf("%s.%s is not answered by %s at all: a caller asks for it with a type assertion, "+
				"which simply stops matching, so the wrapper loses the capability along with its hooks. "+
				"Declare it, or exempt it in this file with the reason it offers nothing", what, name, recorder)
		default:
			t.Errorf("%s.%s is inherited from the embedded surface, so it records nothing: add an "+
				"override that buffers the hook the DoltStorage chain fires for it "+
				"(internal/storage/hook_decorator.go), or exempt it in this file with the reason it fires none",
				what, name)
		}
	}
	for name := range exempt {
		if !present[name] {
			t.Errorf("%s.%s is exempted but no longer exists — delete the exemption", what, name)
		}
	}
}

func interfaceMethods(iface reflect.Type) []string {
	names := make([]string, 0, iface.NumMethod())
	for i := 0; i < iface.NumMethod(); i++ {
		names = append(names, iface.Method(i).Name)
	}
	sort.Strings(names)
	return names
}

