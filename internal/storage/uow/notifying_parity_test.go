// ── The provider's capability surface ───────────────────────────────

// TestNotifyingProviderAnswersTheWholeProviderSurface enumerates what a
// provider offers by PARSING doltSQLProvider's methods out of this package,
// rather than listing them: doltSQLProvider is what every constructor in this
// package returns, so its method set is the surface a caller can reach through
// a UnitOfWorkProvider.
//
// A capability the wrapper does not answer is not a compile error — callers ask
// for these with a type assertion, which simply stops matching — so a role
// accessor added to the provider and forgotten here would silently lose both
// its hooks AND its feature in proxied mode. That is the failure this catches.
func TestNotifyingProviderAnswersTheWholeProviderSurface(t *testing.T) {
	surface := methodsDeclaredOnType(t, "doltSQLProvider")
	if len(surface) < 25 {
		t.Fatalf("parsed only %d methods off doltSQLProvider — the scan is broken, not the provider", len(surface))
	}
	assertPartition(t, "UnitOfWorkProvider", surface, reflect.TypeOf((*notifyingProvider)(nil)), map[string]string{
		"BeginTx": "TxProvider hands out a bare transaction with no unit of work around it, so " +
			"there is nothing to buffer and nothing to drain: the wrapper deliberately does not " +
			"offer it, and only this package's own NewUOW asks a provider for one",
		"initSchema": "unexported provider setup, not a capability any caller can reach",
	})
}

// TestNotifyingProviderBuildsRolesOnItself is the other half of the accessor
// story, and the one reflection cannot see: an accessor that IS declared but
// reads `return NewCommenter(p.inner)` compiles, keeps every type assertion
// working, and silently builds the role on the UNWRAPPED provider — so its
// units of work are plain ones and every hook stops firing. The bodies are
// one-liners, so requiring the receiver to be the constructor's argument is an
// exact check rather than a heuristic.
// It scans the WHOLE package, not notifying.go: this package's convention is a
// file per role, so the accessor most likely to be written next — and to be
// written as a delegation — is the one in the new role's own file.
func TestNotifyingProviderBuildsRolesOnItself(t *testing.T) {
	// The accessors are the provider methods that construct a role; the
	// non-role capabilities forward to the inner provider on purpose.
	forwarders := map[string]bool{
		"NewUOW":        true,
		"Close":         true,
		"RunNonTx":      true,
		"SetPoolLimits": true,
		"Unwrap":        true,
		// Events-journal capability plumbing: activation binds on the inner
		// provider's transactions, and a retention pass writes no bead. Neither
		// builds a role, so neither can build one "on itself".
		"SetEventsJournalEnabled": true,
		"RunEventsMaintenanceTx":  true,
	}

	var checked int
	for _, fn := range funcsDeclaredOnType(t, "notifyingProvider") {
		if forwarders[fn.Name.Name] {
			continue
		}
		receiver := ""
		if len(fn.Recv.List[0].Names) > 0 {
			receiver = fn.Recv.List[0].Names[0].Name
		}
		if !passesReceiver(fn, receiver) {
			t.Errorf("notifyingProvider.%s does not build its role on the wrapper: the role's units "+
				"of work are then the inner provider's, and nothing it writes fires a hook", fn.Name.Name)
		}
		checked++
	}
	if checked < 25 {
		t.Fatalf("checked only %d role accessors — the scan is broken", checked)
	}
}

// TestUnitOfWorkBypassesAreAccountedFor is the third structural guard, and it
// closes the one hole the other two cannot see.
//
// The recorder sits at the USE-CASE seam, so it sees a write only if the write
// passed a use case. A caller that reaches the transaction directly — by
// peeling the decorator with unwrapUOW, or by asserting the concrete unit of
// work — writes rows no hook is fired for, and nothing about that is visible in
// a method set. Today there is exactly one such caller, and it is deliberate;
// the guard is here so that the SECOND one is a decision rather than an
// accident.
func TestUnitOfWorkBypassesAreAccountedFor(t *testing.T) {
	bypasses := map[string]string{
		"importStatementRunner": "the import role runs the shared batch-upsert engine on the " +
			"transaction's statement runner (importer.go), so its writes never pass a use case. " +
			"Import fires no hooks on the DoltStorage plumbing either — it runs the same engine " +
			"there — so this is parity, not a gap. A hook per imported issue would be new " +
			"behavior on both plumbings.",
	}

	found := map[string]bool{}
	for _, fn := range funcsInPackage(t) {
		if !reachesConcreteUOW(fn) {
			continue
		}
		name := fn.Name.Name
		found[name] = true
		reason, ok := bypasses[name]
		switch {
		case !ok:
			t.Errorf("%s reaches the unit of work beneath the recording layer, so whatever it "+
				"writes fires no hook. Route the write through a use case, or list it in this "+
				"test with the reason it fires none", name)
		case strings.TrimSpace(reason) == "":
			t.Errorf("%s is listed as a bypass with no reason", name)
		}
	}
	for name := range bypasses {
		if !found[name] {
			t.Errorf("%s is listed as a bypass but no longer reaches past the recording layer — "+
				"delete the entry", name)
		}
	}
}

// reachesConcreteUOW reports whether fn peels a unit of work down to the
// concrete type — by calling unwrapUOW, or by asserting baseUOW directly.
func reachesConcreteUOW(fn *ast.FuncDecl) bool {
	reaches := false
	ast.Inspect(fn, func(n ast.Node) bool {
		switch node := n.(type) {
		case *ast.CallExpr:
			if ident, ok := node.Fun.(*ast.Ident); ok && ident.Name == "unwrapUOW" {
				reaches = true
			}
		case *ast.TypeAssertExpr:
			if receiverTypeName(node.Type) == "baseUOW" {
				reaches = true
			}
		}
		return true
	})
	return reaches
}

// funcsInPackage parses every non-test file in this package and returns all of
// its function and method declarations.
func funcsInPackage(t *testing.T) []*ast.FuncDecl {
	t.Helper()
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, ".", func(fi fs.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, 0)
	if err != nil {
		t.Fatalf("parse package: %v", err)
	}
	var found []*ast.FuncDecl
	for _, pkg := range pkgs {
		for _, file := range pkg.Files {
			for _, decl := range file.Decls {
				if fn, ok := decl.(*ast.FuncDecl); ok {
					found = append(found, fn)
				}
			}
		}
	}
	return found
}

// passesReceiver reports whether fn hands the receiver itself to a call.
func passesReceiver(fn *ast.FuncDecl, receiver string) bool {
	found := false
	ast.Inspect(fn, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		for _, arg := range call.Args {
			if ident, ok := arg.(*ast.Ident); ok && ident.Name == receiver {
				found = true
			}
		}
		return true
	})
	return found
}

// methodsDeclaredOnType returns the names of the methods this package declares
// on the named receiver type.
func methodsDeclaredOnType(t *testing.T, typeName string) []string {
	t.Helper()
	var names []string
	for _, fn := range funcsDeclaredOnType(t, typeName) {
		names = append(names, fn.Name.Name)
	}
	sort.Strings(names)
	return names
}

// funcsDeclaredOnType parses EVERY non-test file in this package and returns
// the declarations whose receiver is typeName. Both structural guards read the
// package rather than one file: a role lives in its own file here, so a scan
// pinned to notifying.go would not see the accessor a new role adds — which is
// the one most likely to be written as a delegation.
func funcsDeclaredOnType(t *testing.T, typeName string) []*ast.FuncDecl {
	t.Helper()
	var found []*ast.FuncDecl
	for _, fn := range funcsInPackage(t) {
		if fn.Recv == nil || len(fn.Recv.List) == 0 {
			continue
		}
		if receiverTypeName(fn.Recv.List[0].Type) == typeName {
			found = append(found, fn)
		}
	}
	return found
}

func receiverTypeName(expr ast.Expr) string {
	if star, ok := expr.(*ast.StarExpr); ok {
		expr = star.X
	}
	if ident, ok := expr.(*ast.Ident); ok {
		return ident.Name
	}
	return ""
}
